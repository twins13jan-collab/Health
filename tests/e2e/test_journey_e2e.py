import uuid
from _common import call, login, find_id, report
R = []
admin = login('smoke@health.gov.eg')
R.append(('admin logged in', bool(admin), 200))
nid = '2990101' + uuid.uuid4().hex[:7]
s, b = call('POST', '/api/patients', {'nationalId': nid, 'fullName': 'مريض رحلة متكاملة', 'birthDate': '1990-05-01', 'gender': 'M'}, admin)
pid = find_id(b, 'patient')
R.append(('REAL patient registered in the patient module', s in (200, 201) and bool(pid), s))
s, b = call('POST', '/api/encounters', {'patientId': pid, 'type': 'emergency', 'chiefComplaint': 'ألم صدر', 'triageLevel': 2}, admin)
eid = find_id(b, 'encounter')
R.append(('REAL encounter opened for the same patient', s in (200, 201) and bool(eid), s))
s, b = call('POST', '/api/journeys', {'patientId': pid, 'encounterId': eid}, admin)
j = (b.get('journey') or {}).get('id'); corr = b.get('correlation_id')
R.append(('journey started under one correlation id', s == 200 and bool(j) and bool(corr), s))
def step(key, module, etype, entity):
    return call('POST', f'/api/journeys/{j}/steps', {'stepKey': key, 'module': module, 'entityType': etype, 'entityId': entity, 'detail': 'e2e'}, admin)
s, b = step('registration', 'patient', 'patient', pid)
R.append(('step: registration linked (real patient id)', s == 200, s))
s, b = step('encounter', 'clinical', 'encounter', eid)
R.append(('step: encounter linked', s == 200, s))
s, b = call('POST', '/api/journeys/' + j + '/complete', None, admin)
R.append(('completing with only the opening steps -> 409, missing spine named', s == 409, s))
s, b = call('POST', '/api/labs/orders', {'patientId': pid, 'encounterId': eid, 'testCode': 'TROP-I', 'testName': 'تروبونين', 'priority': 'STAT'}, admin)
oid = find_id(b, 'order')
R.append(('REAL lab order created in the labs module for the same encounter', s in (200, 201) and bool(oid), s))
s, b = call('POST', f'/api/labs/orders/{oid}/results', {'value': 0.04, 'unit': 'ng/mL', 'refLow': 0.0, 'refHigh': 0.04}, admin)
R.append(('REAL lab result entered', s in (200, 201), s))
s, b = step('diagnostics', 'labs', 'lab_order', oid)
R.append(('step: diagnostics linked to the real lab order', s == 200, s))
s, b = call('POST', '/api/pharmacy/prescriptions', {'patientId': pid, 'encounterId': eid, 'drugCode': 'ASP-100', 'drugName': 'أسبرين 100', 'dose': '100mg', 'frequency': 'daily', 'duration': '30d'}, admin)
rxid = find_id(b, 'prescription')
R.append(('REAL prescription created in the pharmacy module', s in (200, 201) and bool(rxid), s))
s, b = step('pharmacy', 'pharmacy', 'prescription', rxid)
R.append(('step: pharmacy linked', s == 200, s))
s, b = step('pharmacy', 'pharmacy', 'prescription', rxid)
R.append(('linking the SAME record twice -> 409 (idempotent, no duplicates)', s == 409, s))
s, b = call('POST', '/api/billing/invoices', {'patientId': pid, 'encounterId': eid, 'payer': 'insurance'}, admin)
iid = find_id(b, 'invoice')
R.append(('REAL invoice created in the billing module', s in (200, 201) and bool(iid), s))
s, b = step('billing', 'finance', 'invoice', iid)
R.append(('step: billing linked', s == 200, s))
s, b = step('triage', 'emergency', 'encounter', eid)
R.append(('going BACKWARDS to triage after billing -> 409', s == 409, s))
s, b = call('POST', '/api/admissions-deep/admissions', {'patientRef': pid, 'justification': 'ألم صدر يحتاج ملاحظة', 'priority': 'urgent', 'specialty': 'cardiology', 'transfer': False, 'receivingAccepted': True}, admin)
aid = find_id(b, 'admission')
call('POST', f'/api/admissions-deep/admissions/{aid}/admit', None, admin)
s, b = call('POST', f'/api/admissions-deep/admissions/{aid}/discharge-summary', {'diagnoses': 'ذبحة مستقرة', 'procedures': 'قسطرة تشخيصية', 'instructions': 'راحة وأدوية منتظمة', 'warnings': 'عد فورًا عند ألم صدر', 'medications': 'أسبرين 100', 'followUp': 'عيادة قلب بعد أسبوعين'}, admin)
dsid = find_id(b, 'summary') or aid
R.append(('REAL discharge summary created in the admissions module', s in (200, 201) and bool(dsid), s))
s, b = step('discharge', 'admissions', 'discharge_summary', dsid)
R.append(('step: discharge linked to the real discharge summary', s == 200, s))
s, b = call('POST', '/api/journeys/' + j + '/complete', None, admin)
R.append(('journey COMPLETES with its full spine present', s == 200 and b.get('status') == 'completed', s))
s, b = call('GET', f'/api/journeys/{j}/timeline', None, admin)
steps = b.get('steps') or []; evts = b.get('events') or []
R.append(('timeline shows the whole path in order (6 steps)', s == 200 and len(steps) == 6, s))
R.append(('domain events written to the outbox under the same correlation id (>=7)', len(evts) >= 7 and all(e.get('correlationId') == corr for e in evts), s))
report(R)
